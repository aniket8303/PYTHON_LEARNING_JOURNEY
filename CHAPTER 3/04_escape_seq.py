# ============================================================
#              MOST-USED ESCAPE CHARACTERS IN PYTHON
# ============================================================


# 1. \n - New Line
# Moves the text to the next line

print("Hello\nWorld")

# Output:
# Hello
# World


# 2. \t - Tab
# Adds horizontal tab spacing

print("Name\tAge")
print("Aniket\t21")

# Output:
# Name    Age
# Aniket  21


# 3. \\ - Backslash
# Used to print a backslash

print("C:\\Users\\Aniket\\Documents")

# Output:
# C:\Users\Aniket\Documents


# 4. \" - Double Quote
# Used to include double quotes inside a double-quoted string

print("He said, \"Hello!\"")

# Output:
# He said, "Hello!"


# 5. \' - Single Quote
# Used to include a single quote inside a single-quoted string

print('It\'s Python')

# Output:
# It's Python


# 6. \r - Carriage Return
# Moves the cursor to the beginning of the current line

print("Hello\rWorld")

# Behavior may depend on the terminal.


# 7. \b - Backspace
# Moves the cursor one position backward

print("Hello\b!")

# Behavior may depend on the terminal.


# 8. \f - Form Feed
# Moves to the next page/form-feed position.
# Rarely used in modern programs.

print("Hello\fWorld")


# ============================================================
#                 MOST IMPORTANT TO REMEMBER
# ============================================================

# \n   -> New Line
# \t   -> Tab
# \\   -> Backslash
# \"   -> Double Quote
# \'   -> Single Quote